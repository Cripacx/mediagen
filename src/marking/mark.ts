/**
 * AI content marking.
 *
 * The EU AI Act splits disclosure into two duties, so this is two independent
 * switches rather than one setting:
 *
 * - the provider's duty to make synthetic content **machine-readable**, met by
 *   writing the IPTC/XMP `DigitalSourceType`;
 * - the deployer's duty to **disclose it to people**, met by compositing a
 *   visible label into the media.
 *
 * Both default to off, because both are the caller's decision to make.
 *
 * **On C2PA.** A manifest only carries provenance if it is signed, and signing
 * needs a certificate the user does not have. A test-signed manifest looks
 * like provenance while carrying none, which is worse than no manifest at all.
 * Nothing here writes one; the IPTC/XMP marker needs no certificate and is
 * what platforms actually read.
 *
 * **Provider metadata is never discarded.** If a file already declares a
 * digital source type, its metadata is left alone and that is reported. If it
 * carries other metadata without a source type, the marker is added to it
 * rather than replacing it.
 */

import { readFile, writeFile } from 'node:fs/promises'
import * as path from 'node:path'
import { ERROR_CODE, MediagenError } from '../core/errors.js'
import { mimeForExtension, sniffMediaType } from '../core/mediaType.js'

/** IPTC controlled-vocabulary term for content generated by a trained model. */
export const TRAINED_ALGORITHMIC_MEDIA =
  'http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia'

const IPTC_EXT_NAMESPACE = 'http://iptc.org/std/Iptc4xmpExt/2008-02-29/'
const XMP_NAMESPACE = 'http://ns.adobe.com/xap/1.0/'

/** Text placed on the media when a visible disclosure is requested. */
const VISIBLE_LABEL_TEXT = 'AI-generated'

/**
 * Formats this build can mark.
 *
 * Honesty here beats a promise: XMP in a video container is
 * a different operation from XMP in a still, and this build does not do it.
 * A video is refused by name instead of being silently left unmarked, which
 * would leave a caller believing a disclosure duty had been met.
 */
const MARKABLE_MIME_TYPES = new Set(['image/png', 'image/jpeg', 'image/webp'])

export interface MarkingOptions {
  /** Write the machine-readable IPTC/XMP marker. */
  readonly machineReadable: boolean
  /** Composite a visible disclosure into the media. */
  readonly visibleLabel: boolean
}

/** What produced the media, recorded alongside the marker. */
export interface MarkingProvenance {
  readonly provider?: string
  readonly model?: string
}

export interface MarkingResult {
  readonly filePath: string
  /** True when this call wrote the machine-readable marker. */
  readonly machineReadableWritten: boolean
  /** True when the file already carried a digital source type. */
  readonly alreadyMarked: boolean
  /** True when a visible label was composited in. */
  readonly visibleLabelWritten: boolean
}

/** True when a packet already declares any digital source type. */
export function hasDigitalSourceType(xmp: string | undefined): boolean {
  return typeof xmp === 'string' && /DigitalSourceType/i.test(xmp)
}

export async function markFile(
  filePath: string,
  options: MarkingOptions,
  provenance: MarkingProvenance = {},
): Promise<MarkingResult> {
  if (!options.machineReadable && !options.visibleLabel) {
    return {
      filePath,
      machineReadableWritten: false,
      alreadyMarked: false,
      visibleLabelWritten: false,
    }
  }

  const original = await readFile(filePath).catch(() => {
    throw new MediagenError(ERROR_CODE.FILE_ERROR, `Cannot read ${filePath}.`, {
      hint: 'Check the path and that the file is readable.',
    })
  })

  requireMarkable(filePath, original)

  // Loaded here rather than at module scope: sharp is a native dependency and
  // a run that marks nothing should not pay to load it.
  const sharp = (await import('sharp')).default

  const existing = await sharp(original).metadata()
  const existingXmp = existing.xmp?.toString('utf-8')
  const alreadyMarked = hasDigitalSourceType(existingXmp)

  let pipeline = sharp(original).keepMetadata()

  if (options.visibleLabel) {
    const label = buildLabelSvg(existing.width ?? 1024, existing.height ?? 1024)
    pipeline = pipeline.composite([{ input: label, gravity: 'southeast' }])
  }

  // A file that already declares a source type is left alone and reported.
  // Overwriting would discard whatever the provider recorded about itself.
  const machineReadableWritten = options.machineReadable && !alreadyMarked
  if (machineReadableWritten) {
    pipeline = pipeline.withXmp(
      existingXmp === undefined
        ? buildXmpPacket(provenance)
        : injectIntoXmp(existingXmp, provenance),
    )
  }

  const marked = await pipeline.toBuffer().catch((error: unknown) => {
    throw new MediagenError(ERROR_CODE.FILE_ERROR, `Could not mark ${path.basename(filePath)}.`, {
      hint: 'The file may be corrupt or in a format this build cannot rewrite.',
      cause: error,
    })
  })

  await writeFile(filePath, marked).catch(() => {
    throw new MediagenError(ERROR_CODE.FILE_ERROR, `Cannot write ${filePath}.`, {
      hint: 'Check that the file is not read-only.',
    })
  })

  return {
    filePath,
    machineReadableWritten,
    alreadyMarked,
    visibleLabelWritten: options.visibleLabel,
  }
}

function requireMarkable(filePath: string, data: Uint8Array): void {
  const mimeType = sniffMediaType(data)?.mimeType ?? mimeForExtension(path.extname(filePath))

  if (mimeType !== undefined && MARKABLE_MIME_TYPES.has(mimeType)) return

  const described = mimeType ?? 'an unrecognised format'

  throw new MediagenError(
    ERROR_CODE.VALIDATION_ERROR,
    `This build cannot mark ${described}. It marks ${[...MARKABLE_MIME_TYPES].join(', ')}.`,
    {
      hint: described.startsWith('video/')
        ? 'Writing XMP into a video container is a different operation from writing it into a still, and is not implemented.'
        : 'Convert the file to PNG, JPEG or WebP first.',
    },
  )
}

/** Escapes text for inclusion in XML character data or an attribute value. */
function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function buildProperties(provenance: MarkingProvenance): string {
  const creatorTool = escapeXml([provenance.provider, provenance.model].filter(Boolean).join(' '))

  const lines = [
    `<Iptc4xmpExt:DigitalSourceType>${TRAINED_ALGORITHMIC_MEDIA}</Iptc4xmpExt:DigitalSourceType>`,
  ]
  if (creatorTool.length > 0) {
    lines.push(`<xmp:CreatorTool>${creatorTool}</xmp:CreatorTool>`)
  }
  return lines.join('')
}

/** A complete XMP packet, used when the file carries no XMP at all. */
function buildXmpPacket(provenance: MarkingProvenance): string {
  return [
    '<?xpacket begin="" id="W5M0MpCehiHzreSzNTczkc9d"?>',
    '<x:xmpmeta xmlns:x="adobe:ns:meta/">',
    '<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">',
    '<rdf:Description rdf:about=""',
    ` xmlns:Iptc4xmpExt="${IPTC_EXT_NAMESPACE}"`,
    ` xmlns:xmp="${XMP_NAMESPACE}">`,
    buildProperties(provenance),
    '</rdf:Description>',
    '</rdf:RDF>',
    '</x:xmpmeta>',
    '<?xpacket end="w"?>',
  ].join('')
}

/**
 * Adds the marker to an existing packet rather than replacing it, so provider
 * metadata such as model identifiers survives.
 */
function injectIntoXmp(existing: string, provenance: MarkingProvenance): string {
  const descriptionMatch = /<rdf:Description\b[^>]*>/.exec(existing)
  if (!descriptionMatch) {
    // No element to extend; a fresh packet is the only option.
    return buildXmpPacket(provenance)
  }

  let openingTag = descriptionMatch[0]
  if (!openingTag.includes('xmlns:Iptc4xmpExt')) {
    openingTag = openingTag.replace(/>$/, ` xmlns:Iptc4xmpExt="${IPTC_EXT_NAMESPACE}">`)
  }
  if (!openingTag.includes('xmlns:xmp=')) {
    openingTag = openingTag.replace(/>$/, ` xmlns:xmp="${XMP_NAMESPACE}">`)
  }

  const insertAt = descriptionMatch.index + descriptionMatch[0].length
  return (
    existing.slice(0, descriptionMatch.index) +
    openingTag +
    buildProperties(provenance) +
    existing.slice(insertAt)
  )
}

/**
 * SVG banner composited into the bottom-right corner.
 *
 * The label grows with the image so it stays legible on a 4K render, and is
 * clamped so it still fits on a small one. Without the clamp a thumbnail
 * fails outright — sharp refuses to composite something larger than its
 * canvas — which would turn a disclosure request into an error.
 */
function buildLabelSvg(width: number, height: number): Buffer {
  const shortest = Math.min(width, height)
  let fontSize = Math.max(9, Math.round((14 * shortest) / 400))
  let paddingX = Math.round((fontSize * 10) / 14)
  let paddingY = Math.round((fontSize * 6) / 14)

  const measure = (size: number, padding: number): number =>
    Math.round(size * 0.62 * VISIBLE_LABEL_TEXT.length + padding * 2)

  // Leave a little breathing room rather than filling the edge exactly.
  const available = Math.max(1, Math.floor(width * 0.96))

  if (measure(fontSize, paddingX) > available) {
    const ratio = available / measure(fontSize, paddingX)
    fontSize = Math.max(6, Math.floor(fontSize * ratio))
    paddingX = Math.max(2, Math.floor(paddingX * ratio))
    paddingY = Math.max(1, Math.floor(paddingY * ratio))
  }

  const boxWidth = Math.min(available, measure(fontSize, paddingX))
  const boxHeight = Math.min(Math.max(1, height), fontSize + paddingY * 2)

  return Buffer.from(
    [
      `<svg xmlns="http://www.w3.org/2000/svg" width="${boxWidth}" height="${boxHeight}">`,
      `<rect x="0" y="0" width="${boxWidth}" height="${boxHeight}" rx="${Math.round(
        boxHeight / 5,
      )}" fill="rgba(0,0,0,0.62)"/>`,
      `<text x="${paddingX}" y="${paddingY + fontSize * 0.8}" font-family="sans-serif" font-size="${fontSize}" fill="#ffffff">${VISIBLE_LABEL_TEXT}</text>`,
      '</svg>',
    ].join(''),
  )
}
